import re
import platform
import subprocess
import os

try:
    from distutils.msvccompiler import MSVCCompiler, get_build_architecture
except ImportError:
    try:
        from setuptools._distutils.msvccompiler import MSVCCompiler, get_build_architecture
    except ImportError:
        # Python 3.12+: distutils.msvccompiler was removed from CPython and newer setuptools.
        MSVCCompiler = None
        def get_build_architecture():
            m = platform.machine().upper()
            if m in ('AMD64', 'X86_64') or m.endswith('64'):
                return 'AMD64'
            return 'x86'


if MSVCCompiler is not None:
    compiler = MSVCCompiler()
    compiler.initialize()
else:
    compiler = None
_fmt_header = ';\n; Definition file of %s\n; Generated by vstools\n;\n'


class DumpbinError(Exception):
    pass

class DumpbinParseError(DumpbinError):
    pass


def find_symbols(dll):
    if compiler is not None:
        dumpbin_path = compiler.find_exe('dumpbin.exe')
    else:
        dumpbin_path = _find_msvc_tool('dumpbin.exe')
        if dumpbin_path is None:
            raise DumpbinError(
                "dumpbin.exe not found. Install Visual Studio Build Tools."
            )
    try:
        output = subprocess.check_output(
            [dumpbin_path, '/nologo', '/exports', dll],
            universal_newlines=True,
        )
    except subprocess.CalledProcessError as e:
        raise DumpbinError(e.output)

    lines = output.split('\n')

    it = iter(lines)

    found = False
    for line in it:
        if 'name' in line:
            found = True
            break

    if not found:
        raise DumpbinParseError

    next(it)
    next(it)
    next(it)

    symbols = []
    exp = re.compile(r'\w+')

    for line in it:
        if not line.strip():
            break
        symbols.append(exp.findall(line)[3])

    return symbols

def _find_msvc_tool(name):
    """Find an MSVC tool like dumpbin.exe or lib.exe by searching known VS paths."""
    import shutil
    # Check PATH first
    found = shutil.which(name)
    if found:
        return found
    # Search Visual Studio / Build Tools install directories
    import glob as _glob
    search_roots = [
        r'C:\Program Files (x86)\Microsoft Visual Studio',
        r'C:\Program Files\Microsoft Visual Studio',
    ]
    for root in search_roots:
        pattern = os.path.join(root, '**', name)
        results = _glob.glob(pattern, recursive=True)
        # Prefer HostX64/x64 or HostX86/x64 variants
        for r in results:
            if 'HostX' in r and 'x64' in r:
                return r
        if results:
            return results[0]
    return None

def _msvc_tools_available():
    """Return True if dumpbin.exe and lib.exe are usable."""
    if compiler is not None:
        return True
    return _find_msvc_tool('dumpbin.exe') is not None

def dump_def(dll, def_file=None):
    if not _msvc_tools_available():
        print(f"WARNING: Skipping .def generation for {os.path.basename(dll)} "
              f"(MSVC tools not available). Build may still succeed with prebuilt libs.")
        return
    if not def_file:
        def_file = f'{os.path.splitext(dll)[0]}.def'
    dll_base = os.path.basename(dll)
    with open(def_file, 'w') as f:
        f.write(_fmt_header % dll_base)
        f.write(f'LIBRARY "{dll_base}\"\n')
        f.write('EXPORTS\n')
        f.writelines(f"{line}\n" for line in find_symbols(dll))

def lib_from_def(def_file, arch=None):
    if not _msvc_tools_available():
        print(f"WARNING: Skipping .lib generation for {os.path.basename(def_file)} "
              f"(MSVC tools not available). Build may still succeed with prebuilt libs.")
        return
    if not arch:
        arch = get_build_architecture()
        if arch == 'Intel':
            arch = 'x86'
        elif arch == 'Itanium':
            arch = 'IA64'
        else:
            arch = 'x64'
    lib_file = f'{os.path.splitext(def_file)[0]}.lib'
    if compiler is not None:
        compiler.spawn([compiler.lib, '/nologo', f'/MACHINE:{arch}',
                       f'/DEF:{def_file}', f'/OUT:{lib_file}'])
    else:
        lib_exe = _find_msvc_tool('lib.exe')
        if lib_exe is None:
            raise DumpbinError("lib.exe not found. Install Visual Studio Build Tools.")
        subprocess.check_call([lib_exe, '/nologo', f'/MACHINE:{arch}',
                               f'/DEF:{def_file}', f'/OUT:{lib_file}'])
